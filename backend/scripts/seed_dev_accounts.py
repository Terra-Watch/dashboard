"""Create repeatable local-only TerraWatch development accounts.

This command refuses non-loopback database hosts and requires an explicit
confirmation flag. It changes only the three reserved *.dev@terrawatch.local
accounts and writes generated credentials to backend/.dev-credentials.
"""

from __future__ import annotations

import argparse
import os
import secrets
import sys
from pathlib import Path
from urllib.parse import urlparse

from dotenv import load_dotenv
from sqlalchemy import text

BACKEND = Path(__file__).resolve().parents[1]
REPO = BACKEND.parent
sys.path.insert(0, str(BACKEND))
load_dotenv(BACKEND / ".env")

from app.core.security import hash_password_argon2  # noqa: E402
from app.database.session import engine  # noqa: E402


ACCOUNTS = (
    ("citizen.dev@terrawatch.local", "TerraWatch Local Citizen", "citizen", None),
    ("ranger.dev@terrawatch.local", "TerraWatch Local Ranger", "field_crew", "OD"),
    ("controlroom.dev@terrawatch.local", "TerraWatch Local Control Room", "control_room_operator", "OD"),
)
LOCAL_HOSTS = {"localhost", "127.0.0.1", "::1"}
CREDENTIALS_FILE = BACKEND / ".dev-credentials"


def _database_host() -> str:
    value = os.environ.get("DATABASE_URL", "")
    parsed = urlparse(value)
    return parsed.hostname or ""


def _password() -> str:
    # URL-safe characters keep the generated value easy to paste into forms.
    return f"TWdev-{secrets.token_urlsafe(18)}"


def main() -> int:
    parser = argparse.ArgumentParser(description="Seed local TerraWatch development accounts")
    parser.add_argument(
        "--confirm-local",
        action="store_true",
        help="confirm that the configured database is a loopback development database",
    )
    args = parser.parse_args()
    host = _database_host()
    if not args.confirm_local:
        parser.error("refusing to seed accounts without --confirm-local")
    if host not in LOCAL_HOSTS:
        parser.error(f"refusing to seed accounts: DATABASE_URL host is not loopback ({host or 'missing'})")

    credentials: list[tuple[str, str, str]] = []
    with engine.begin() as db:
        for email, name, role, home_state in ACCOUNTS:
            password = _password()
            existing = db.execute(text("SELECT id FROM resq_users WHERE email=:email"), {"email": email}).scalar()
            if existing:
                db.execute(
                    text("""UPDATE resq_users
                        SET name=:name, role=:role, home_state=:home_state,
                            password_hash=:password_hash, password_algo='argon2'
                        WHERE id=:id"""),
                    {
                        "id": existing,
                        "name": name,
                        "role": role,
                        "home_state": home_state,
                        "password_hash": hash_password_argon2(password),
                    },
                )
                user_id = existing
            else:
                user_id = db.execute(
                    text("""INSERT INTO resq_users
                        (email,name,password_hash,password_algo,role,home_state)
                        VALUES (:email,:name,:password_hash,'argon2',:role,:home_state)
                        RETURNING id"""),
                    {
                        "email": email,
                        "name": name,
                        "password_hash": hash_password_argon2(password),
                        "role": role,
                        "home_state": home_state,
                    },
                ).scalar_one()

            db.execute(
                text("""INSERT INTO resq_user_settings (user_id)
                    VALUES (:user_id) ON CONFLICT (user_id) DO NOTHING"""),
                {"user_id": user_id},
            )
            if role != "citizen":
                for state in ("OD", "CG", "TS", "MP", "MH", "JH"):
                    db.execute(
                        text("""INSERT INTO resq_user_scopes (user_id,state)
                            VALUES (:user_id,:state) ON CONFLICT DO NOTHING"""),
                        {"user_id": user_id, "state": state},
                    )
            credentials.append((email, password, role))

    lines = [
        "TerraWatch LOCAL DEVELOPMENT CREDENTIALS",
        "Generated by backend/scripts/seed_dev_accounts.py",
        "Do not commit or share this file.",
        "",
    ]
    for email, password, role in credentials:
        lines.extend((f"[{role}]", f"email={email}", f"password={password}", ""))
    flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC
    fd = os.open(CREDENTIALS_FILE, flags, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as output:
        output.write("\n".join(lines))
    print(f"Seeded {len(credentials)} local development accounts.")
    print(f"Credentials written to {CREDENTIALS_FILE} (mode 600).")
    for email, password, role in credentials:
        print(f"{role}: {email} / {password}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
